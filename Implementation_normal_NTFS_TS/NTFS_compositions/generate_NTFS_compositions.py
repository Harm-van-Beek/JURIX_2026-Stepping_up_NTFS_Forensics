# Generate compositions of NTFS operations needed for identifying normal NTFS timestamp structures under our restriction
# We need to define these compositions as strings containing "apply(S,operation_name).". 
# "apply(S,operation_name)." denotes that operation_name is perfomed at step S. 

# To obtain these compositions, we define the compositions given by lemma 1 and lemma 2 as follows:

list_compositions_1: list[list[str]] = [
    ['operation_re'],
    ['operation_up','operation_re'],
    ['operation_at','operation_re'],
    ['operation_up','operation_at','operation_re'],
    ['operation_ov','operation_re'],
    ['operation_ov','operation_up','operation_re'],
    ['operation_ov','operation_up','operation_at','operation_re'],
    ['operation_oc','operation_re']
]

list_of_compositions_2: list[list[str]] = [
    ['operation_ac'],
    ['operation_up'],
    ['operation_at'],
    ['operation_up','operation_at'],
    ['operation_ov'],
    ['operation_ov', 'operation_up'],
    ['operation_ov', 'operation_up', 'operation_at'],
    ['operation_oc']
]

# Construct_facts translates list‑based compositions into atoms like "apply(S,operation_name)".

def construct_facts(compositions_as_lists: list[str]) -> str:
    list_of_facts = [f"apply({operation_position},{operation_name})" for operation_position, operation_name in enumerate(compositions_as_lists)]
    compositions_as_facts = ". ".join(list_of_facts) + "."
    return compositions_as_facts

# Construct_compositions defines the compositions by lemma 1 and lemma 2 as facts for ASP

def construct_compositions(compositions_as_lists: list[list[str]]) -> list[str]:
    list_of_compositions_as_facts = []
    for composition in compositions_as_lists:       
        composition_as_facts = construct_facts(composition)
        list_of_compositions_as_facts.append(composition_as_facts)
    return list_of_compositions_as_facts

# Construct_and_combine_compositions defines the compositions by theorem 1 as facts for ASP

def construct_and_combine_compositions(compositions_as_lists_1: list[list[str]],compositions_as_lists_2: list[list[str]]) -> list[str]:
    list_of_compositions = []
    for composition_1 in compositions_as_lists_1:
        for composition_2 in compositions_as_lists_2:
            composition_3 = composition_1 + composition_2         
            composition_as_facts = construct_facts(composition_3)
            list_of_compositions.append(composition_as_facts)
    return list_of_compositions


# Generate compositions of NTFS operations needed for identifying reachable NTFS timestamp structures under our restriction
# We store these compositions in the file ntfs_compositions.py.

def write_ntfs_compositions():
    
    ntfs_compositions = construct_compositions(list_compositions_1) 
    ntfs_compositions += construct_compositions(list_of_compositions_2) 
    ntfs_compositions += construct_and_combine_compositions(list_compositions_1,list_of_compositions_2)

    file_name = "NTFS_compositions.py"
    with open(file_name, "w") as file:
        file.write("# -------------------------------------------------------------------------------------------------------------\n")
        file.write("# Compositions of NTFS operations needed for identifying normal NTFS timestamp structures under our restriction\n")
        file.write("# -------------------------------------------------------------------------------------------------------------\n")
        file.write("\n")
        file.write("# The compositions have been generated by the running the file ntfs_compositions_generate.py.\n")
        file.write("# We compositions by facts of form \"apply(S,operation_name).\".\n")
        file.write("# apply(S,operation_name) denotes that operation_name is perfomed at step S.\n")
        file.write("\n")
        file.write("ntfs_compositions: list[str] = [ \n")

        for composition in ntfs_compositions:
            file.write(f' "{composition}",\n')

        file.write("]\n")
    
    return print(f'{len(ntfs_compositions)} compositions of NTFS operations have been written.')

if __name__ == "__main__":
    write_ntfs_compositions()