# -------------------------------------------------------------------------------------------------------------
# Functions for identifying T-normal NTFS timestamp structures with ASP (clingo) under our restriction
# -------------------------------------------------------------------------------------------------------------


def compute_normal_NTFS_TS_instance(composition: str,initial_TS: str) -> list[dict]:
    
    program = clingo.Control(["0"])
    program.load("search_normal_NTFS_TS.lp")
    program.add("base", [], composition)
    program.add("base", [], initial_TS)
    program.ground([("base", [])])

    ranking_list = [] 

    for model in program.solve(yield_=True):         
        rank_dict = {}           

        for relation in model.symbols(atoms=True):

            if relation.name != "rank":          
                continue                    

            temporal_feature = str(relation.arguments[0])

            rank_dict[temporal_feature] = relation.arguments[1].number

        ranking_list.append(rank_dict)

    return remove_duplicates_TS_as_dict(ranking_list)


def remove_duplicates_TS_as_dict(list_of_TS: list[dict]) -> list[dict]:
    set_of_TS = { tuple(sorted(ranking.items())) for ranking in list_of_TS }
    list_of_TS_without_duplicates = [dict(ranking_as_tuple) for ranking_as_tuple in set_of_TS]
    return list_of_TS_without_duplicates


def compute_normal_NTFS_TS(list_compositions: list[str],list_initial_TS: list[str]) -> list[dict]:
    normal_TS = []
    total_composition = len(list_compositions)
    count_composition = 0

    for composition in list_compositions:
        count_composition += 1
        print('------------------------------------------------------------------------------------------')
        print(f'I am looking at a new composition; {total_composition - count_composition} compositions are remaining.')
        print('------------------------------------------------------------------------------------------')


        total_initial_TS = len(list_initial_TS)
        count_initial_TS = 0

        for starting_TS in list_initial_TS:
            
            count_initial_TS += 1
            print(f'I am looking at a new initial NTFS timestamp structure for this composition; {total_initial_TS - count_initial_TS} initial timestamp structures are remaining.')
            normal_TS += compute_normal_NTFS_TS_instance(composition,starting_TS)      
    
    return remove_duplicates_TS_as_dict(normal_TS)


# -------------------------------------------------------------------------------------------------------------
# Functions for human-readable representation of T-normal NTFS timestamp structures
# -------------------------------------------------------------------------------------------------------------

def human_readable_TS(TS_dict: dict) -> list[list]:

    remaining = ['si_1', 'si_2', 'si_3', 'si_4', 'fn_1', 'fn_2', 'fn_3', 'fn_4']
    TS_as_list = []
    
    while remaining:
        values = [TS_dict[feature] for feature in remaining]
        max_value = max(values)
        temporal_features_with_same_rank = [feature for feature in remaining if TS_dict[feature] == max_value]
        TS_as_list.append(temporal_features_with_same_rank)
        remaining = [feature for feature in remaining if feature not in temporal_features_with_same_rank]
    
    return TS_as_list

def write_normal_NTFS_TS(list_normal_TS: list[dict], output_file: str, description: str, description_name: str): 
    
    with open(output_file, "w") as file:
        file.write("# ------------------------------------------------------------------------------------------\n")
        file.write(f"# T-normal NTFS timestamp structures automatically generated by running main.py.\n")
        file.write(f"# The list is based on initial NTFS timestamp structures {description}.\n")
        file.write("# ------------------------------------------------------------------------------------------\n")
        file.write("\n")
        file.write(f"# Each entry of the list is a T-normal NTFS timestamp structure.\n")
        file.write("# Each entry in such a list (i.e. timestamp structure) is a set of timestamp features of same rank.\n")
        file.write("# That is, an equivalence class of temporal features w.r.t. the timestamp structure considered.\n")
        file.write("# The leftmost set of timestamp features contain maximal temporal features w.r.t. the timestamp structure considered.\n")
        file.write("# The rightmost set of timestamp features contain minimal temporal features w.r.t. the timestamp structure considered.\n")
        file.write("\n")
        file.write(f"normal_NTFS_TS{description_name} = [\n")

        for structure in list_normal_TS:
            rank = human_readable_TS(structure)
            file.write(f"    {repr(rank)},\n")

        file.write("]\n")

