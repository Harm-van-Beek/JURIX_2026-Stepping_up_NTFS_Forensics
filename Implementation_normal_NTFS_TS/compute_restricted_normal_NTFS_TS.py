from normal_NTFS_TS.normal_NTFS_TS import normal_NTFS_TS

# -------------------------------------------------------------------------------------------------------------
# Functions for deducing T\{si_4,fn_4}-normal NTFS timestamp strucutures from T-normal NTFS timestamp structures
# -------------------------------------------------------------------------------------------------------------

def remove_duplicates_TS_lists(list_TS: list[list[str]]) -> list[list[str]]:
    set_seen_rankings = set()
    list_unique_rankings = []
    
    for TS in list_TS:
        
        # Convert list of equivalence classes of features into tuple of tuples
        TS_as_tuple = tuple(tuple(feature) for feature in TS)
        
        if TS_as_tuple not in set_seen_rankings: 
            set_seen_rankings.add(TS_as_tuple)
            list_unique_rankings.append(TS)
    
    return list_unique_rankings


def restrict_human_readable_TS(list_TS: list[list[str]], exclude_features: set) -> list[list[str]]:
    
    list_restricted_TS = []

    for TS in list_TS:
        restricted_TS = []  # 

        for equivalence_class in TS:  # Was: equialence_class
            equivalence_class_restricted = [feature for feature in equivalence_class if feature not in exclude_features]

            if equivalence_class_restricted:
                restricted_TS.append(equivalence_class_restricted)

        if restricted_TS:
            list_restricted_TS.append(restricted_TS)

    return list_restricted_TS

def write_restricted_human_readable_TS(list_TS: list[list[str]], exclude_features: set, output_file: str):
    
     with open(output_file, "w") as file:
        file.write("# ------------------------------------------------------------------------------------------\n")
        file.write(f"# T\\{exclude_features}-normal NTFS timestamp structures automatically generated by running main.py.\n")
        file.write("# ------------------------------------------------------------------------------------------\n")
        file.write("\n")
        file.write(f"# Each entry of the list is a T\\{exclude_features}-normal NTFS timestamp structure.\n")
        file.write("# Each entry in such a list (i.e. timestamp structure) is a set of timestamp features of same rank.\n")
        file.write("# That is, an equivalence class of temporal features w.r.t. the timestamp structure considered.\n")
        file.write("# The leftmost set of timestamp features contain maximal temporal features w.r.t. the timestamp structure considered.\n")
        file.write("# The rightmost set of timestamp features contain minimal temporal features w.r.t. the timestamp structure considered.\n")
        file.write("\n")
        file.write(f"normal_NTFS_TS_restricted = [\n")

        for TS in list_TS:
            file.write(str(TS) + ",\n")
        
        file.write("]\n")


# -------------------------------------------------------------------------------------------------------------
# Identifying T\{si_4,fn_4}-normal NTFS timestamp strucutures from T-normal NTFS timestamp structures
# -------------------------------------------------------------------------------------------------------------


def identify_normal_NTFS_TS_restricted():

    restricted_normal_NTFS_TS = remove_duplicates_TS_lists(restrict_human_readable_TS(normal_NTFS_TS,{'si_4','fn_4'}))

    write_restricted_human_readable_TS(
        list_TS=restricted_normal_NTFS_TS,
        exclude_features={'si_4','fn_4'},
        output_file="normal_NTFS_TS/normal_NTFS_TS_restricted.py",
    )

    print("File with T\\{si_4,fn_4}-normal NTFS timestamp structures not considering file tunneling is written.")
    print(f"{len(restricted_normal_NTFS_TS)} T\\{{si_4,fn_4}}-normal NTFS timestamp structures  not considering file tunneling have been found.")

    
if __name__ == "__main__":
    identify_normal_NTFS_TS_restricted()